CREATE VIEW [Items].[v_ItemSharedVendor]
AS
SELECT t.ID,
       t.SharedID,
       t1.Name,
       t1.Barcode,
       t1.Barcodes,
       t.VendorID,
       t.Vendor,
       t.ItemCode,
       t.UnitIs,
       t.CurrencyID,
       t.Currency,
       t.Price,
       t.PriceF,
       t.PriceD,
       t.DescriptionIs,
       t.DateCreate
FROM Items.t_ItemSharedVendor AS t
    LEFT OUTER JOIN Items.t_ItemShared AS t1
        ON t.SharedID = t1.ID;



